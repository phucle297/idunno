#!/usr/bin/env python3
"""T44 A5 perf summary from heavy.log + perf/*.log. Prints and writes PERF_SUMMARY.md."""
import re, pathlib, statistics as st
P = pathlib.Path(__file__).resolve().parent
log = (P.parent / "heavy.log").read_text()
pat = re.compile(r"PERF_4P label=(\S+) avg_ms=([\d.]+) p95_ms=([\d.]+) max_ms=([\d.]+) draw_calls=(\d+) primitives=(\d+)")
g = {"B": [], "Aoff": [], "Aoff_info": [], "Aon": []}
for lab, avg, p95, mx, dc, pr in pat.findall(log):
    k = "Aoff_info" if "vsAon" in lab else "Aon" if lab.startswith("Aon_") else "Aoff" if lab.startswith("Aoff_") else "B"
    g[k].append((float(avg), float(p95), int(pr)))
m = lambda xs, i: sum(x[i] for x in xs) / len(xs)
out = []
def row(name, a, b, i, lim):
    pct = (m(a, i) - m(b, i)) / m(b, i) * 100
    verdict = "n/a" if lim is None else ("within ceiling" if pct <= lim else ("OVER ceiling by %.1fpp (info)" % (pct - lim) if lim == 50 else "FAIL"))
    return f"| {name} | {m(a,i):.2f} | {m(b,i):.2f} | {pct:+.1f}% | {'<=+%d%%' % lim if lim is not None else 'info'} | {verdict} |"
out += ["## 4P moving bench (toy_town, 4 players moving, 90 frames/run, llvmpipe 1280x720)",
        f"### Gate: A5 AA-off (override.cfg) vs B ae933edd, {len(g['Aoff'])} vs {len(g['B'])} interleaved runs",
        "| metric | A5 AA-off | B | delta | gate | |", "|---|---|---|---|---|---|",
        row("avg ms", g["Aoff"], g["B"], 0, 10), row("p95 ms", g["Aoff"], g["B"], 1, 10), row("primitives", g["Aoff"], g["B"], 2, 5), "",
        f"### Info: AA-on vs AA-off on the A5 tree, {len(g['Aon'])} vs {len(g['Aoff_info'])} interleaved runs (ceiling +50%)",
        "| metric | AA-on | AA-off | delta | ceiling | |", "|---|---|---|---|---|---|",
        row("avg ms", g["Aon"], g["Aoff_info"], 0, 50), row("p95 ms", g["Aon"], g["Aoff_info"], 1, 50), row("primitives", g["Aon"], g["Aoff_info"], 2, None), ""]
tr = {}
for f in sorted(P.glob("trace_*_run*.log")):
    mm = re.search(r"trace_(B|Aoff)_run(\d+)", f.name)
    t = re.search(r'INDOOR_TRACE overall=\{[^}]*"avg": ([\d.]+), "p95": ([\d.]+), "max": ([\d.]+)', f.read_text())
    if t and mm:
        tr[(mm.group(1), int(mm.group(2)))] = (float(t.group(1)), float(t.group(2)), float(t.group(3)))
out += ["## Interior trace (render_indoor_lighting --mode=trace, overall p95 ms)", "| run | B | A5 AA-off | pair delta p95 |", "|---|---|---|---|"]
pairs = []
for i in range(1, 7):
    b, a = tr.get(("B", i)), tr.get(("Aoff", i))
    if b and a:
        pairs.append((b, a))
    out.append(f"| {i} | {b[1] if b else '-'} | {a[1] if a else '-'} | {('%+.1f%%' % ((a[1]-b[1])/b[1]*100)) if (a and b) else '-'} |")
if pairs:
    bp = sum(b[1] for b, a in pairs) / len(pairs); ap = sum(a[1] for b, a in pairs) / len(pairs)
    pct = (ap - bp) / bp * 100
    out += ["", f"Complete pairs: {len(pairs)} (plan asks >=6). Mean p95 A5 AA-off {ap:.2f} vs B {bp:.2f} = {pct:+.1f}% (gate <=+10%): {'PASS' if pct <= 10 else 'FAIL'} on these {len(pairs)} pairs.",
            f"Median of pair deltas: {st.median([(a[1]-b[1])/b[1]*100 for b, a in pairs]):+.1f}%.",
            "Unpaired extra runs: " + ", ".join(f"{k[0]}{k[1]}={v[1]}" for k, v in sorted(tr.items()) if not (("B", k[1]) in tr and ("Aoff", k[1]) in tr)) ]
(P / "PERF_SUMMARY.md").write_text("# T44 A5 perf summary (generated by summarize.py)\n\n" + "\n".join(out) + "\n")
print("\n".join(out))
